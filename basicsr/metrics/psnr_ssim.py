def _prepare_face_weight(face_weight, target_shape, crop_border=0, mask_threshold=1):
    if face_weight is None:
        raise ValueError('face_weight is required for face-region metrics.')

    mask = np.asarray(face_weight)
    if mask.ndim == 3:
        if mask.shape[0] == 1 and mask.shape[1:] == target_shape:
            mask = mask[0]
        elif mask.shape[-1] == 1:
            mask = mask[..., 0]
        else:
            raise ValueError(f'face_weight should be single-channel, but got shape {face_weight.shape}.')
    if mask.ndim != 2:
        raise ValueError(f'face_weight should be 2D or single-channel 3D, but got shape {face_weight.shape}.')
    if mask.shape != target_shape:
        raise ValueError(f'face_weight shape {mask.shape} is incompatible with image shape {target_shape}.')

    mask = mask.astype(np.float64)
    max_value = mask.max() if mask.size > 0 else 0
    threshold = mask_threshold / 255.0
    normalizer = 255.0 if max_value > 1.0 else 1.0
    mask = np.clip(mask / normalizer, 0.0, 1.0)
    mask = np.where(mask >= threshold, mask, 0.0)

    if crop_border != 0:
        mask = mask[crop_border:-crop_border, crop_border:-crop_border]
    if mask.size == 0 or mask.sum() <= 0:
        raise ValueError('face_weight does not contain any valid face-region pixels.')
    return mask


