@METRIC_REGISTRY.register()
def calculate_face_psnr(img, img2, face_weight, crop_border, input_order='HWC', test_y_channel=False, mask_threshold=1,
                        **kwargs):
    """Calculate PSNR on the offline face-weighted region."""

    assert img.shape == img2.shape, (f'Image shapes are different: {img.shape}, {img2.shape}.')
    if input_order not in ['HWC', 'CHW']:
        raise ValueError(f'Wrong input_order {input_order}. Supported input_orders are "HWC" and "CHW"')
    img = reorder_image(img, input_order=input_order)
    img2 = reorder_image(img2, input_order=input_order)
    face_weight = _prepare_face_weight(face_weight, img.shape[:2], crop_border, mask_threshold)
    img = img.astype(np.float64)
    img2 = img2.astype(np.float64)

    if crop_border != 0:
        img = img[crop_border:-crop_border, crop_border:-crop_border, ...]
        img2 = img2[crop_border:-crop_border, crop_border:-crop_border, ...]

    if test_y_channel:
        img = to_y_channel(img)
        img2 = to_y_channel(img2)

    mse = np.sum(((img - img2)**2) * face_weight[..., None]) / (np.sum(face_weight) * img.shape[2])
    if mse == 0:
        return float('inf')
    return 20. * np.log10(255. / np.sqrt(mse))


@METRIC_REGISTRY.register()
def calculate_face_ssim(img, img2, face_weight, crop_border, input_order='HWC', test_y_channel=False, mask_threshold=1,
                        **kwargs):
    """Calculate SSIM on the offline face-weighted region."""

    assert img.shape == img2.shape, (f'Image shapes are different: {img.shape}, {img2.shape}.')
    if input_order not in ['HWC', 'CHW']:
        raise ValueError(f'Wrong input_order {input_order}. Supported input_orders are "HWC" and "CHW"')
    img = reorder_image(img, input_order=input_order)
    img2 = reorder_image(img2, input_order=input_order)
    face_weight = _prepare_face_weight(face_weight, img.shape[:2], crop_border, mask_threshold)
    img = img.astype(np.float64)
    img2 = img2.astype(np.float64)

    if crop_border != 0:
        img = img[crop_border:-crop_border, crop_border:-crop_border, ...]
        img2 = img2[crop_border:-crop_border, crop_border:-crop_border, ...]

    if test_y_channel:
        img = to_y_channel(img)
        img2 = to_y_channel(img2)

    face_weight = face_weight[5:-5, 5:-5]
    if face_weight.size == 0 or face_weight.sum() <= 0:
        raise ValueError('face_weight does not contain valid pixels after SSIM border cropping.')

    ssims = []
    for i in range(img.shape[2]):
        ssim_map = _ssim_map(img[..., i], img2[..., i])
        ssims.append(np.sum(ssim_map * face_weight) / np.sum(face_weight))
    return np.array(ssims).mean()
